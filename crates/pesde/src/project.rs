/// A workspace member. Can be empty for the root project.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(transparent)]
pub struct Importer(VfsPath);

impl Importer {
	/// Take great care when constructing an `Importer` from a `VfsPath`.
	/// They are required to be workspace members, and the root importer is
	/// represented by an empty path. Usually, `Project::workspace_members`
	/// should be used to obtain importers.
	#[must_use]
	pub fn from_path(path: VfsPath) -> Self {
		Self(path)
	}

	/// An importer pointing to the project root
	#[must_use]
	pub fn root() -> Self {
		Self(VfsPath::root())
	}

	/// Whether this importer is the root importer
	#[must_use]
	pub fn is_root(&self) -> bool {
		(*self.0).is_empty()
	}

	pub(crate) fn join(&self, other: &VfsPath) -> VfsPath {
		self.0.join(other)
	}
}

impl Display for Importer {
	fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
		if self.is_root() {
			write!(f, "(root)")
		} else {
			write!(f, "{}", self.0)
		}
	}
}

impl Deref for Importer {
	type Target = VfsPath;

	fn deref(&self) -> &Self::Target {
		&self.0
	}
}

#[derive(Debug, Default)]
struct WorkspaceCache {
	manifests: HashMap<Importer, Arc<tokio::sync::OnceCell<Arc<Manifest>>>>,
	members_by_name: HashMap<PackageName, Importer>,
}

/// A workspace, representing the package side of a project.
#[derive(Debug, Clone)]
pub struct Workspace {
	cache: Arc<Mutex<WorkspaceCache>>,
	vfs: Arc<dyn Vfs>,
	reduced_trust: bool,
}

impl Workspace {
	/// The virtual file system.
	#[must_use]
	pub fn vfs(&self) -> Arc<dyn Vfs> {
		self.vfs.clone()
	}

	/// Create a workspace member for an importer.
	/// ## Warning
	/// Be sure that the importer actually belongs to this workspace. Otherwise, unexpected behavior may occur.
	#[must_use]
	pub fn member(self, importer: Importer) -> WorkspaceMember {
		WorkspaceMember {
			workspace: self,
			importer,
		}
	}

	/// Deserialize the lockfile
	#[instrument(skip(self), ret(level = "trace"), level = "debug")]
	pub async fn deser_lockfile(&self) -> Result<Resolution> {
		if self.reduced_trust {
			return Err(Error::reduced_trust());
		}

		let path = LOCKFILE_FILE_NAME.parse().unwrap();
		let mut buf = String::new();
		match self.vfs().read_file(&path).await {
			Ok(mut file) => {
				file.read_to_string(&mut buf)
					.await
					.map_err(|e| Error::vfs(e, path.clone()))?;

				lockfile::parse_lockfile(&buf).map_err(Into::into)
			}
			Err(e) => Err(Error::vfs(e, path)),
		}
	}

	/// Write the lockfile
	#[instrument(skip(self, resolution), level = "debug")]
	pub async fn write_lockfile(&self, resolution: &Resolution) -> Result<()> {
		if self.reduced_trust {
			return Err(Error::reduced_trust());
		}

		let resolution = toml::to_string(resolution).map_err(Error::lockfile_write)?;
		let lockfile = format!(
			r"# This file is automatically @generated by pesde.
# It is not intended for manual editing.
format = {}
{resolution}",
			lockfile::CURRENT_FORMAT
		);
		let path = LOCKFILE_FILE_NAME.parse().unwrap();
		self.vfs()
			.write_file(&path, lockfile.as_bytes())
			.await
			.map_err(|e| Error::vfs(e, path))?;
		Ok(())
	}

	pub(crate) fn members(&self) -> impl Stream<Item = Result<Importer>> {
		try_stream!({
			let root = VfsPath::root();

			if self.reduced_trust {
				yield Importer(root);
				return;
			}

			let root_subproject = self.clone().member(Importer::root());
			let root_manifest = root_subproject.deser_manifest().await?;

			let stream = root_manifest.workspace.members.matches(self.vfs(), &root);
			let mut stream = std::pin::pin!(stream);
			let mut emitted_root = false;

			while let Some(member) = stream.try_next().await? {
				if member.is_empty() {
					emitted_root = true;
				}
				yield Importer(member);
			}

			if !emitted_root {
				yield Importer(root.clone());
			}
		})
	}

	pub(crate) async fn members_with_manifests(
		&self,
	) -> JoinSet<Result<(WorkspaceMember, Arc<Manifest>)>> {
		self.members()
			.map_ok(|importer| self.clone().member(importer))
			.map(|result| async move {
				match result {
					Ok(member) => {
						let manifest = member.deser_manifest().await?;
						Ok((member, manifest))
					}
					Err(e) => Err(e),
				}
			})
			.collect::<JoinSet<_>>()
			.await
	}
}

/// A [Workspace] member.
#[derive(Debug, Clone)]
pub struct WorkspaceMember {
	workspace: Workspace,
	importer: Importer,
}

impl WorkspaceMember {
	/// The workspace this member belongs to.
	#[must_use]
	pub fn workspace(&self) -> &Workspace {
		&self.workspace
	}

	/// The importer path
	#[must_use]
	pub fn importer(&self) -> &Importer {
		&self.importer
	}

	/// Split the workspace member into its components
	#[must_use]
	pub fn into_parts(self) -> (Workspace, Importer) {
		(self.workspace, self.importer)
	}

	/// Read the manifest file
	#[instrument(skip(self), fields(importer = %self.importer()), ret(level = "trace"), level = "debug")]
	pub async fn read_manifest(&self) -> Result<String> {
		let path = self.importer().join(&MANIFEST_FILE_NAME.parse().unwrap());
		let mut buf = String::new();

		match self.workspace().vfs().read_file(&path).await {
			Ok(mut file) => {
				file.read_to_string(&mut buf)
					.await
					.map_err(|e| Error::vfs(e, path))?;

				Ok(buf)
			}
			Err(e) => Err(Error::vfs(e, path)),
		}
	}

	/// Deserialize the manifest file
	#[instrument(skip(self), fields(importer = %self.importer()), ret(level = "trace"), level = "debug")]
	pub async fn deser_manifest(&self) -> Result<Arc<Manifest>> {
		let (my_cell, root_cell) = {
			let mut cache = self.workspace().cache.lock().unwrap();
			let my_cell = cache
				.manifests
				.entry(self.importer().clone())
				.or_default()
				.clone();
			let root_cell = (!self.importer().is_root())
				.then(|| cache.manifests.entry(Importer::root()).or_default().clone());
			(my_cell, root_cell)
		};

		if self.workspace().reduced_trust {
			let manifest = my_cell.get().ok_or_else(Error::reduced_trust)?.clone();
			return Ok(manifest);
		}

		let root = if let Some(root_cell) = root_cell {
			let root = root_cell
				.get_or_try_init(|| async {
					let root_subproject = self.workspace().clone().member(Importer::root());
					let root_manifest_str = root_subproject.read_manifest().await?;
					parse_manifest(&root_manifest_str, None)
						.map(Arc::new)
						.map_err(|e| Error::manifest(e, root_subproject.importer().clone()))
				})
				.await?
				.clone();
			Some(root)
		} else {
			None
		};

		let manifest = my_cell
			.get_or_try_init(|| async {
				let manifest_str = self.read_manifest().await?;
				parse_manifest(&manifest_str, root.as_deref())
					.map(Arc::new)
					.map_err(|e| Error::manifest(e, self.importer().clone()))
			})
			.await
			.map(Arc::clone)?;

		{
			let mut cache = self.workspace.cache.lock().unwrap();
			if let Some(other) = cache
				.members_by_name
				.insert(manifest.package.name.clone(), self.importer().clone())
				&& other != *self.importer()
			{
				return Err(Error::duplicate_member(
					self.importer().clone(),
					other,
					manifest.package.name.clone(),
				));
			}
		}

		Ok(manifest)
	}

	/// Write the manifest file
	#[instrument(skip(self, manifest), fields(importer = %self.importer()), level = "debug")]
	pub async fn write_manifest(&self, manifest: impl AsRef<[u8]>) -> Result<()> {
		if self.workspace().reduced_trust {
			return Err(Error::reduced_trust());
		}

		let path = self.importer().join(&MANIFEST_FILE_NAME.parse().unwrap());
		self.workspace()
			.vfs()
			.write_file(&path, manifest.as_ref())
			.await
			.map_err(|e| Error::vfs(e, path))?;

		let mut cache = self.workspace().cache.lock().unwrap();

		if self.importer().is_root() {
			cache.manifests.clear();
			cache.members_by_name.clear();
		} else {
			cache.manifests.remove(self.importer());
			cache.members_by_name.retain(|_, v| v != self.importer());
		}

		Ok(())
	}
}

/// The implementer side of a project, containing the [Workspace] and [SourceProvider].
#[derive(Clone)]
pub struct Project {
	workspace: Workspace,
	source_provider: Arc<dyn SourceProvider>,
}

impl Debug for Project {
	fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
		f.debug_struct("Project")
			.field("workspace", &self.workspace)
			.finish()
	}
}

impl Project {
	/// Create a new `Project`.
	pub fn new(
		vfs: Arc<dyn Vfs>,
		make_provider: impl FnOnce(&Workspace) -> Arc<dyn SourceProvider>,
	) -> Self {
		let workspace = Workspace {
			vfs,
			cache: Default::default(),
			reduced_trust: false,
		};

		Project {
			source_provider: make_provider(&workspace),
			workspace,
		}
	}

	/// Create a new `Project` for a published package, used for e.g. `pesde x`.
	/// This mode has reduced trust and will assume a published structure.
	#[must_use]
	pub fn for_published_package(
		vfs: Arc<dyn Vfs>,
		make_provider: impl FnOnce(&Workspace) -> Arc<dyn SourceProvider>,
		manifest: Arc<Manifest>,
	) -> Self {
		let cache = WorkspaceCache {
			manifests: HashMap::from([(
				Importer::root(),
				Arc::new(tokio::sync::OnceCell::from(manifest)),
			)]),
			members_by_name: Default::default(),
		};

		let workspace = Workspace {
			vfs,
			cache: Arc::new(Mutex::new(cache)),
			reduced_trust: true,
		};

		Project {
			source_provider: make_provider(&workspace),
			workspace,
		}
	}

	/// The workspace of the project.
	#[must_use]
	pub fn workspace(&self) -> &Workspace {
		&self.workspace
	}

	/// Create a workspace member for an importer.
	/// ## Warning
	/// Be sure that the importer actually belongs to this workspace. Otherwise, unexpected behavior may occur.
	#[must_use]
	pub fn member(&self, importer: Importer) -> WorkspaceMember {
		WorkspaceMember {
			workspace: self.workspace.clone(),
			importer,
		}
	}

	/// The package source implementations.
	#[must_use]
	pub fn source_provider(&self) -> &dyn SourceProvider {
		&*self.source_provider
	}
}
